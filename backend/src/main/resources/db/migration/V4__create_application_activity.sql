CREATE TABLE application_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL CHECK (type IN ('CREATED', 'STATUS_CHANGED')),
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_activity_application FOREIGN KEY (application_id)
        REFERENCES job_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_activity_owner FOREIGN KEY (owner_id) REFERENCES app_users(id)
);

CREATE INDEX idx_activity_owner_recent ON application_activity(owner_id, occurred_at DESC, id DESC);
CREATE INDEX idx_activity_application_recent ON application_activity(application_id, occurred_at DESC, id DESC);
