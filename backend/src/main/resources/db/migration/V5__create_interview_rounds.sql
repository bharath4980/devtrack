-- Interview preparation is additive; existing job application fields remain unchanged.
CREATE TABLE interview_rounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    round_name VARCHAR(120) NOT NULL,
    scheduled_date DATE,
    format VARCHAR(32) NOT NULL CHECK (format IN ('PHONE', 'VIDEO', 'ONSITE', 'TAKE_HOME', 'OTHER')),
    contact_name VARCHAR(255),
    contact_email VARCHAR(254),
    preparation_notes VARCHAR(2000),
    follow_up_notes VARCHAR(2000),
    outcome VARCHAR(32) NOT NULL CHECK (outcome IN ('PLANNED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_interview_application FOREIGN KEY (application_id)
        REFERENCES job_applications(id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_owner FOREIGN KEY (owner_id)
        REFERENCES app_users(id)
);
CREATE INDEX idx_interview_owner_application ON interview_rounds(owner_id, application_id, id);
